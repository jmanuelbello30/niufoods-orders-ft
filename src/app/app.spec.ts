import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    const app = fixture.componentInstance;
    expect(app).toBeTruthy();
  });

  it('should render the header and router outlet', () => {
    const fixture = TestBed.createComponent(App);
    fixture.detectChanges();
    const compiled = fixture.nativeElement as HTMLElement;
    expect(compiled.querySelector('.site-header__title')?.textContent).toContain('Panel de órdenes');
    expect(compiled.querySelector('img')?.getAttribute('src')).toBe('/images/niu-foods-logo.jpg');
    expect(compiled.querySelector('router-outlet')).not.toBeNull();
  });
});
